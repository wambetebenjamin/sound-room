#!/usr/bin/env python3
"""
build_worship_set.py — render a full Sunday set: long arrangements, sequenced.

Takes worship chord charts, builds a **full song form** (intro, verses, choruses,
bridge, big final chorus, outro) for each one — around 3 minutes rather than a
40-second loop — masters every track to -14 LUFS, then joins them into one
continuous set with crossfades.

Everything is generated by our own code: no samples, no loops, no third-party audio.

Usage:
    python3 scripts/build_worship_set.py                          # the built-in set
    python3 scripts/build_worship_set.py --tempo 0=66             # override a tempo
    python3 scripts/build_worship_set.py --chart a.onsong --key C --tempo 70 ...
"""
from __future__ import annotations

import argparse
import sys
from dataclasses import replace
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

from backing_from_chart import read_chart  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
CHART_DIR = ROOT / "tools/worship-charts"
OUT = ROOT / "demos" / "sunday-set"

# A three-song set with a deliberate arc: intimate -> gathering -> celebration.
# Charts normally do not carry a tempo (most default to 72), so tempos are set here.
SET = [
    ("Goodness of God.onsong", None, 63),
    ("Amazing Grace (Graveson version).onsong", None, 72),
    ("This Is Amazing Grace.onsong", None, 98),
]

SR = 44100
TARGET_LUFS = -14.0


def master(audio: np.ndarray, sr: int) -> np.ndarray:
    import enhance_audio as E
    chain = replace(E.PRESETS["neutral"], target_lufs=TARGET_LUFS, ceiling_db=-1.0)
    return E.normalize(audio, sr, chain)


def encode(audio: np.ndarray, sr: int, path: Path) -> None:
    import soundfile as sf
    path.parent.mkdir(parents=True, exist_ok=True)
    sf.write(path, audio, sr, format="MP3")


def crossfade_join(tracks: list[np.ndarray], sr: int, fade: float = 1.5) -> np.ndarray:
    """Join mastered tracks. Kept in float32 on purpose: the whole set is ~8 minutes,
    and re-mastering that in float64 with 4x true-peak oversampling exhausts RAM."""
    n = int(fade * sr)
    out = tracks[0].astype(np.float32, copy=True)
    for nxt in tracks[1:]:
        k = min(n, len(out), len(nxt))
        ramp = np.linspace(0.0, 1.0, k, dtype=np.float32)[:, None]
        tail = out[-k:] * (1.0 - ramp)
        head = nxt[:k] * ramp
        out = np.concatenate([out[:-k], tail + head, nxt[k:]])
    return out


def safe_trim(audio: np.ndarray, ceiling_db: float = -1.2) -> tuple[np.ndarray, float]:
    """Crossfades can push the sum a little hot; trim the whole set by one scalar
    so the balance between songs is untouched."""
    peak = float(np.max(np.abs(audio)))
    if peak <= 0:
        return audio, 0.0
    peak_db = 20 * np.log10(peak)
    if peak_db <= ceiling_db:
        return audio, 0.0
    trim = ceiling_db - peak_db
    return audio * (10 ** (trim / 20)), trim


def render(spec) -> tuple[str, str, float, np.ndarray]:
    from build_worship_arrangement import DEFAULT_FORM, SR as SYNTH_SR, build

    chart, key_override, tempo = spec
    info = read_chart(CHART_DIR / chart)
    key = key_override or info["key"]
    audio = build(key, tempo, None, SYNTH_SR, chords=info["progression"], form=DEFAULT_FORM)
    return info["title"], key, tempo, audio


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tempo", action="append", default=[],
                    help="override tempo for song N, e.g. --tempo 0=66")
    ap.add_argument("--chart", action="append", default=[],
                    help="use a specific chart instead of the built-in set")
    ap.add_argument("--fade", type=float, default=1.5, help="crossfade seconds")
    ap.add_argument("--reuse", action="store_true",
                    help="reuse already-rendered tracks in the output dir")
    args = ap.parse_args()

    spec = list(SET)
    if args.chart:
        spec = [(c, None, 72) for c in args.chart]
    for ov in args.tempo:
        idx, val = ov.split("=")
        i = int(idx)
        if i < len(spec):
            chart, key, _ = spec[i]
            spec[i] = (chart, key, float(val))

    OUT.mkdir(parents=True, exist_ok=True)
    tracks, rows = [], []
    import soundfile as sf
    for i, s in enumerate(spec, 1):
        chart, key_override, tempo = s
        info = read_chart(CHART_DIR / chart)
        key = key_override or info["key"]
        title = info["title"]
        slug = f"{i:02d}-" + "".join(c if c.isalnum() else "-" for c in title.lower()).strip("-")[:40]
        existing = OUT / f"{slug}.mp3"

        if args.reuse and existing.exists():
            audio, _ = sf.read(existing, dtype="float32")
            print(f"  {i}. reusing {existing.name} ({len(audio)/SR:.1f}s)", flush=True)
        else:
            audio = render(s)[3]
            audio = master(audio, SR)
            encode(audio, SR, existing)
            print(f"  {i}. {title[:36]:<38} {key:<4} {tempo:>5.0f} BPM  {len(audio)/SR:6.1f}s", flush=True)

        tracks.append(np.asarray(audio, dtype=np.float32))
        rows.append((title, key, tempo, len(audio) / SR))

    total = sum(r[3] for r in rows) - args.fade * (len(rows) - 1)
    print(f"  set total ~{int(total)//60}:{int(total)%60:02d}")

    if len(tracks) > 1:
        joined = crossfade_join(tracks, SR, args.fade)
        joined, trim = safe_trim(joined)
        encode(joined, SR, OUT / "00-complete-set.mp3")
        if trim:
            print(f"  trimmed {trim:+.2f} dB to keep true peak in check", flush=True)
        print(f"  continuous set -> {OUT/'00-complete-set.mp3'} "
              f"({len(joined)/SR/60:.1f} min)", flush=True)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
